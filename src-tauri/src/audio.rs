//! Per-application volume and mute through the Windows Core Audio session API.
//!
//! SMTC (see `media.rs`) knows *what* is playing but not how loud it is, and
//! `IAudioSessionControl2` is the only way to change one app's level without
//! touching the system mixer. Sessions are matched to SMTC sources by process
//! name; Chromium players publish an opaque AUMID, so for those we fall back to
//! the loudest session, which is almost always the one that is audible.

use windows::core::Interface;
use windows::Win32::Media::Audio::Endpoints::IAudioMeterInformation;
use windows::Win32::Media::Audio::{
    eConsole, eRender, IAudioSessionControl2, IAudioSessionManager2, IMMDeviceEnumerator,
    ISimpleAudioVolume, MMDeviceEnumerator,
};
use windows::Win32::System::Com::{CoCreateInstance, CLSCTX_ALL};

use crate::winapi_ext;

struct Session {
    process: String,
    volume: ISimpleAudioVolume,
    peak: f32,
}

fn manager() -> Option<IAudioSessionManager2> {
    unsafe {
        let enumerator: IMMDeviceEnumerator =
            CoCreateInstance(&MMDeviceEnumerator, None, CLSCTX_ALL).ok()?;
        let device = enumerator.GetDefaultAudioEndpoint(eRender, eConsole).ok()?;
        device.Activate(CLSCTX_ALL, None).ok()
    }
}

fn sessions() -> Vec<Session> {
    let Some(manager) = manager() else {
        return Vec::new();
    };
    let Ok(enumerator) = (unsafe { manager.GetSessionEnumerator() }) else {
        return Vec::new();
    };
    let count = unsafe { enumerator.GetCount() }.unwrap_or(0);
    let mut out = Vec::with_capacity(count as usize);
    for index in 0..count {
        let Ok(control) = (unsafe { enumerator.GetSession(index) }) else {
            continue;
        };
        let Ok(control2) = control.cast::<IAudioSessionControl2>() else {
            continue;
        };
        let Ok(pid) = (unsafe { control2.GetProcessId() }) else {
            continue;
        };
        let Some(process) = winapi_ext::process_name(pid) else {
            continue;
        };
        let Ok(volume) = control.cast::<ISimpleAudioVolume>() else {
            continue;
        };
        let peak = control
            .cast::<IAudioMeterInformation>()
            .ok()
            .and_then(|meter| unsafe { meter.GetPeakValue() }.ok())
            .unwrap_or(0.0);
        out.push(Session {
            process,
            volume,
            peak,
        });
    }
    out
}

/// Process hint from an AUMID: `Spotify.exe` → `spotify`. Empty for the
/// auto-generated ids that Chromium-based players use.
fn hint(app_id: &str) -> String {
    let base = app_id.rsplit('!').next().unwrap_or(app_id);
    let base = base.split('_').next().unwrap_or(base);
    let lower = base.trim_end_matches(".exe").to_lowercase();
    if lower.starts_with("microsoft.autogenerated") || lower.contains('{') {
        return String::new();
    }
    lower
}

fn find<'a>(list: &'a [Session], app_id: &str) -> Option<&'a Session> {
    let name = hint(app_id);
    if !name.is_empty() {
        // A named app must match exactly: never fall back to another app's
        // session, or the slider would change the wrong volume.
        return list.iter().find(|session| session.process == name);
    }
    // Opaque AUMID (Chromium players): the loudest session is the best guess.
    list.iter()
        .filter(|session| session.peak > 0.001)
        .max_by(|a, b| {
            a.peak
                .partial_cmp(&b.peak)
                .unwrap_or(std::cmp::Ordering::Equal)
        })
}

/// Current level (0..100) and mute flag of the app's audio session.
pub fn volume(app_id: &str) -> Option<(u32, bool)> {
    let list = sessions();
    let session = find(&list, app_id)?;
    let level = unsafe { session.volume.GetMasterVolume() }.ok()?;
    let muted = unsafe { session.volume.GetMute() }.ok()?.as_bool();
    Some(((level.clamp(0.0, 1.0) * 100.0).round() as u32, muted))
}

pub fn set_volume(app_id: &str, level: u32) -> Result<(), String> {
    let list = sessions();
    let session = find(&list, app_id).ok_or_else(|| "no audio session".to_string())?;
    let value = level.min(100) as f32 / 100.0;
    unsafe { session.volume.SetMasterVolume(value, std::ptr::null()) }.map_err(|e| e.to_string())
}

pub fn set_mute(app_id: &str, muted: bool) -> Result<(), String> {
    let list = sessions();
    let session = find(&list, app_id).ok_or_else(|| "no audio session".to_string())?;
    unsafe { session.volume.SetMute(muted, std::ptr::null()) }.map_err(|e| e.to_string())
}
